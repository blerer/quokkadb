//! Typed model fields, expressions, and collection operations.
//!
//! Start with [`crate::QuokkaDB::typed_collection`] and use
//! the generated field proxies inside filter, sort, update, and projection
//! closures. The common expression types are also re-exported at the crate
//! root, while this module is the place to browse the complete typed API when
//! you need explicit type annotations or an advanced integration.
//!
//! ## Where to look
//!
//! - Define models with [`QuokkaDocument`] and embedded values with
//!   [`QuokkaType`]. Use [`QuokkaScalar`] for custom BSON leaf values.
//! - Navigate generated fields with [`crate::typed::Field`],
//!   [`crate::typed::OptionalField`], [`crate::typed::ArrayField`],
//!   [`crate::typed::MapField`], and [`crate::typed::ObjectField`].
//! - Build expressions with [`Filter`], [`Sort`], [`Update`], [`Index`], and
//!   [`not`].
//! - Run typed operations through [`TypedCollection`]. Its methods return
//!   builders such as [`crate::typed::TypedFind`],
//!   [`crate::typed::TypedFindOne`], and [`crate::typed::TypedUpdateOne`].
//!   Most applications can leave these builder types inferred.
//! - Use [`crate::typed::TypedSelection`] with `select`, `include`, or
//!   `exclude` when a query should return a projection instead of the complete
//!   model.
//!
//! The document-oriented API is available through [`crate::Collection`] when
//! the document shape is dynamic. See the [getting started
//! guide](https://github.com/blerer/quokkadb/blob/main/docs/getting-started.md)
//! for the shortest application workflow and the [API
//! reference](https://github.com/blerer/quokkadb/blob/main/docs/api-reference.md)
//! for the complete typed and document APIs.
//!
//! ## Query a typed model
//!
//! A typed collection turns the fields generated by `QuokkaDocument` into
//! compile-time checked expressions. The closure passed to `find` receives
//! those fields, so the query remains tied to the Rust model as it evolves.
//!
//! ```rust,no_run
//! use quokkadb::{QuokkaDB, QuokkaDocument};
//! use serde::{Deserialize, Serialize};
//!
//! #[derive(Debug, Serialize, Deserialize, QuokkaDocument)]
//! struct User {
//!     #[serde(rename = "_id")]
//!     id: u64,
//!     name: String,
//!     age: i32,
//!     active: bool,
//! }
//!
//! # fn main() -> quokkadb::Result<()> {
//! let db = QuokkaDB::open("./my-app-data")?;
//! let users = db.typed_collection::<User>("users").create_if_missing();
//!
//! users.insert_one(User {
//!     id: 1,
//!     name: "Ada".to_owned(),
//!     age: 37,
//!     active: true,
//! })?;
//!
//! let active_users = users
//!     .find(|user| user.active.eq(true))
//!     .sort(|user| user.name.asc())
//!     .limit(20)
//!     .execute_collect()?;
//! # let _ = active_users;
//! # Ok(())
//! # }
//! ```
//!
//! ## Compose updates, indexes, and projections
//!
//! Field methods produce typed [`Filter`], [`Update`], [`Sort`], and [`Index`]
//! values. Combine compatible expressions with methods such as `and` and
//! `then`, and use `select` or `include_without_id` when the result should be
//! smaller than the stored model.
//!
//! ```rust,no_run
//! use quokkadb::{QuokkaDB, QuokkaDocument};
//! use serde::{Deserialize, Serialize};
//!
//! #[derive(Debug, Serialize, Deserialize, QuokkaDocument)]
//! struct User {
//!     #[serde(rename = "_id")]
//!     id: u64,
//!     name: String,
//!     age: i32,
//!     active: bool,
//! }
//!
//! #[derive(Debug, Deserialize)]
//! struct UserSummary {
//!     name: String,
//!     age: i32,
//! }
//!
//! # fn main() -> quokkadb::Result<()> {
//! let db = QuokkaDB::open("./my-app-data")?;
//! let users = db.typed_collection::<User>("users").create_if_missing();
//!
//! users.create_index(|user| user.active.index_desc().then(user.name.index_asc()))?;
//!
//! users.update_one(
//!     |user| user.id.eq(1_u64),
//!     |user| user.active.set(true).and(user.age.inc(1)),
//! )?;
//!
//! let summaries: Vec<UserSummary> = users
//!     .find(|user| user.active.eq(true))
//!     .include_without_id(|user| (user.name, user.age))
//!     .execute_collect()?;
//! # let _ = summaries;
//! # Ok(())
//! # }
//! ```

